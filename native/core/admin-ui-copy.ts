// Only this product-owned prefix and its own fallback are localized. A push
// provider's detail is kept byte-for-byte and is never interpreted as a template.
export function notificationDeliveryNotice(locale: AppLocale, message: string): string {
  const prefix = "Test notification could not be delivered: ";
  if (!message.startsWith(prefix)) return message;
  const detail = message.slice(prefix.length);
  const copy = adminUiCopy(locale);
  return `${copy["Test notification could not be delivered:"]} ${detail === "the push provider rejected it."
    ? copy["the push provider rejected it."]
    : detail}`;
}
