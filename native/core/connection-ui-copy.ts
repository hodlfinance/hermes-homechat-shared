// Web follows the app’s permission explanation; storage and provider actions are unchanged.
export function connectionPermissionLines(kind: "email" | "telegram" | "whatsapp", locale: AppLocale): Array<{ title: string; detail: string }> {
  const copy = connectionUiCopy(locale);
  const shared = [
    {
      title: copy["Only this account"],
      detail: copy["This connection is tied to the person signed in here."],
    },
    {
      title: copy["Saved privately"],
      detail: copy["Secrets are encrypted and hidden after you save them."],
    },
  ];

  if (kind === "email") {
    return [
      { title: copy["Mailbox access"], detail: copy["Email uses only the mailbox details you add here."] },
      ...shared,
      { title: copy["Disconnect anytime"], detail: copy["Removes the saved mail details from this workspace."] },
    ];
  }

  if (kind === "telegram") {
    return [
      { title: copy["Bot access"], detail: copy["Telegram uses only the bot details you add here."] },
      ...shared,
      { title: copy["Disconnect anytime"], detail: copy["Removes the saved bot details from this workspace."] },
    ];
  }

  return [
    { title: copy["WhatsApp access"], detail: copy["WhatsApp uses only the phone number ID and token you add here."] },
    ...shared,
    { title: copy["Disconnect anytime"], detail: copy["Removes the saved WhatsApp details from this workspace."] },
  ];
}

// Substitute only the original template's placeholders. Names and connection
// labels remain literal even when they contain braces or replacement syntax.
export function connectionUiMessage(
  locale: AppLocale,
  message: keyof typeof en,
  values: Readonly<Record<string, string>>,
): string {
  return connectionUiCopy(locale)[message].replace(/\{(\w+)\}/g, (placeholder, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? values[key] ?? placeholder : placeholder,
  );
}
